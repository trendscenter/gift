function stru_results = icatb_fb_gui_postproc(gui_inputs)
% Filterbank post-processing options using GIFT GUI styling

    icatb_defaults;
    global UI_FS;

    % default vals
    n_estimate = 1; % no estimate
    num_clusters = 6;
    fuzzival = 1.5;
    s_dist_method = 'sqEuclidean';
    n_continuous_kmeans = 2; %continuous

    field_names = fieldnames(gui_inputs);
    for n=1:length(field_names)
    
        switch(field_names{n})
            case 'num_clusters'
                num_clusters = gui_inputs.num_clusters;
            case 'fuzzival'
                fuzzival = gui_inputs.fuzzival;                
            case 's_dist_method'
                if strcmpi('City', gui_inputs.s_dist_method)
                    n_dist_method = 1;
                elseif  strcmpi('sqEuclidean', gui_inputs.s_dist_method)
                    n_dist_method = 2;
                elseif  strcmpi('Correlation', gui_inputs.s_dist_method)
                    n_dist_method = 3; 
                elseif  strcmpi('Cosine', gui_inputs.s_dist_method)
                    n_dist_method = 4;                
                end                
            case 'estimate_clusters'
                if strcmpi('no', gui_inputs.estimate_clusters)
                    n_estimate = 1; %set to no
                else
                    n_estimate = 2; %set to yes
                end
            case 'b_continuous_kmeans'
                if gui_inputs.b_continuous_kmeans
                    n_continuous_kmeans = 1; %set to no
                else
                    n_continuous_kmeans = 2; %set to yes
                end   
        end
    end

    % Default outputs (also used if window is closed with X)
    estimateClusters = false;
    numClusters = [];

    gui_y_offset = 0.13;
    gui_y_pos = 0.9;

    % Create GIFT-style window
    fig = icatb_getGraphics('Filterbank Post Processing', ...
        'normal', 'filterbank_postprocessing', 'on');

    set(fig, 'menubar', 'none', ...
        'NumberTitle', 'off', ...
        'WindowStyle', 'normal', ...
        'CloseRequestFcn', @(src,~) delete(src));

    gui_line_num = 0;

    % ESTIM CLUSTERS
    icatb_uicontrol('parent', fig, ...
        'units', 'normalized', ...
        'style', 'text', ...
        'position', [0.08 gui_y_pos-gui_y_offset*gui_line_num 0.50 0.06], ...
        'String', 'Do you want to estimate the number of clusters?', ...
        'fontsize', UI_FS - 1, ...
        'horizontalalignment', 'left');
    % Yes/No dropdown
    answerH = uicontrol('Parent', fig, ...
        'Units', 'normalized', ...
        'Style', 'popupmenu', ...
        'Position', [0.65 gui_y_pos-gui_y_offset*gui_line_num 0.20 0.04], ...
        'String', {'No', 'Yes'}, ...
        'Value', n_estimate, ...
        'FontSize', UI_FS - 1);

    % CLUSTER NUMBER
    gui_line_num=gui_line_num+1;
    icatb_uicontrol('parent', fig, ...
        'units', 'normalized', ...
        'style', 'text', ...
        'position', [0.08 gui_y_pos-gui_y_offset*gui_line_num 0.50 0.06], ...
        'String', 'Please enter the number of cluster centroids:', ...
        'fontsize', UI_FS - 1, ...
        'horizontalalignment', 'left');
    % Numeric textbox
    clusterH = uicontrol('Parent', fig, ...
        'Units', 'normalized', ...
        'Style', 'edit', ...
        'Position', [0.65 gui_y_pos-gui_y_offset*gui_line_num 0.20 0.06], ...
        'String', num2str(num_clusters), ...
        'FontSize', UI_FS - 1, ...
        'HorizontalAlignment', 'left');

    % KMEANS DISTANCE METHOD
    gui_line_num=gui_line_num+1;
    icatb_uicontrol('parent', fig, ...
        'units', 'normalized', ...
        'style', 'text', ...
        'position', [0.08 gui_y_pos-gui_y_offset*gui_line_num 0.50 0.06], ...
        'String', 'Distance type?', ...
        'fontsize', UI_FS - 1, ...
        'horizontalalignment', 'left');
    % DROPDOWN KMEANS DISTANCE METHOD
    dist_methodH = uicontrol('Parent', fig, ...
        'Units', 'normalized', ...
        'Style', 'popupmenu', ...
        'Position', [0.65 gui_y_pos-gui_y_offset*gui_line_num 0.20 0.04], ...
        'String', {'City', 'sqEuclidean', 'Correlation', 'Cosine'}, ...
        'Value', n_dist_method, ...
        'FontSize', UI_FS - 1);    

    % DISCRETE VS CONTINUOUS
    gui_line_num=gui_line_num+1;
    icatb_uicontrol('parent', fig, ...
        'units', 'normalized', ...
        'style', 'text', ...
        'position', [0.08 gui_y_pos-gui_y_offset*gui_line_num 0.50 0.06], ...
        'String', 'Discrete VS continuous KMEANS?', ...
        'fontsize', UI_FS - 1, ...
        'horizontalalignment', 'left');
    % Yes/No dropdown
    continuous_kmeansH = uicontrol('Parent', fig, ...
        'Units', 'normalized', ...
        'Style', 'popupmenu', ...
        'Position', [0.65 gui_y_pos-gui_y_offset*gui_line_num 0.20 0.04], ...
        'String', {'Discrete', 'Continuous'}, ...
        'Value', n_continuous_kmeans, ...
        'FontSize', UI_FS - 1);     

    % CLUSTER NUMBER
    gui_line_num=gui_line_num+1;
    icatb_uicontrol('parent', fig, ...
        'units', 'normalized', ...
        'style', 'text', ...
        'position', [0.08 gui_y_pos-gui_y_offset*gui_line_num 0.50 0.06], ...
        'String', 'Fuzzifier value:', ...
        'fontsize', UI_FS - 1, ...
        'horizontalalignment', 'left');
    % Numeric textbox
    fuzzyH = uicontrol('Parent', fig, ...
        'Units', 'normalized', ...
        'Style', 'edit', ...
        'Position', [0.65 gui_y_pos-gui_y_offset*gui_line_num 0.20 0.06], ...
        'String', num2str(fuzzival), ...
        'FontSize', UI_FS - 1, ...
        'HorizontalAlignment', 'left');     

    % Done button
% Done button
doneH = icatb_uicontrol('parent', fig, ...
    'units', 'normalized', ...
    'style', 'pushbutton', ...
    'position', [0.40 0.07 0.20 0.06], ...
    'String', 'Done', ...
    'fontsize', UI_FS - 1);

% Assign callback explicitly
set(doneH, 'Callback', @doneCallback);

    % Wait until window is deleted
    waitfor(fig);

    % Nested callback
    function doneCallback(~, ~)

        % estimateClusters = (get(answerH, 'Value') == 2);
        num_clusters = str2double(get(clusterH, 'String'));
        fuzzival = str2double(get(fuzzyH, 'String'));

        % Retrieve cluster
        if get(answerH, 'Value') == 2
            estimate_clusters = 'yes';
        else
            estimate_clusters = 'no';
        end

        % Retrieve KMEANS type
        if get(continuous_kmeansH, 'Value') == 2
            b_continuous_kmeans = true;
        else
            b_continuous_kmeans = false;
        end

        % Retrieve kmeans distance
        switch (get(dist_methodH, 'Value'))
            case 1; s_dist_method = 'City';
            case 2; s_dist_method = 'sqEuclidean';
            case 3; s_dist_method = 'Correlation';
            case 4; s_dist_method = 'Cosine';
        end        
        
        stru_results = struct('b_continuous_kmeans', b_continuous_kmeans, 'fuzzival', fuzzival, 's_dist_method', s_dist_method, 'estimate_clusters', estimate_clusters, 'num_clusters', num_clusters);



        % Validate cluster number
        if ~isfinite(num_clusters) || num_clusters < 1 || ...
                num_clusters ~= floor(num_clusters)
            errordlg('Please enter a positive integer.', ...
                'Invalid cluster number');
            return;
        end

        % Close window
        delete(fig);
    end

end