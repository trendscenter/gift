
function icatb_fb_gui()

fig = figure('Name', 'dfnc_toolbox', ...
    'NumberTitle', 'off', ...
    'MenuBar', 'none', ...
    'Color', [0 0 0], ...
    'Units', 'pixels', ...
    'Position', [200 200 560 460], ...
    'Resize', 'off');

% Menus
uimenu(fig, 'Label', 'File');
uimenu(fig, 'Label', 'Tools');
uimenu(fig, 'Label', 'Utils');

% Title panel
p1 = uipanel('Parent', fig, ...
    'Units', 'pixels', ...
    'Position', [32 300 470 85], ...
    'BackgroundColor', [0 0 0], ...
    'ForegroundColor', [1 1 1]);

uicontrol('Parent', p1, ...
    'Style', 'text', ...
    'String', sprintf('Filterbank Toolbox'), ...
    'Units', 'pixels', ...
    'Position', [90 20 290 48], ...
    'BackgroundColor', [0 0 0], ...
    'ForegroundColor', [0 1 1], ...
    'FontSize', 12);

% Button panel
p2 = uipanel('Parent', fig, ...
    'Units', 'pixels', ...
    'Position', [32 32 470 252], ...
    'BackgroundColor', [0 0 0], ...
    'ForegroundColor', [1 1 1]);

labels = {'Setup / Run Analysis', ...
          'Post-processing', ...
          'Display', ...
          'Stats', ...
          'Exit'};

for k = 1:5
    uicontrol('Parent', p2, ...
        'Style', 'pushbutton', ...
        'String', labels{k}, ...
        'Units', 'pixels', ...
        'Position', [152 211-(k-1)*50 166 34], ...
        'FontSize', 9, ...
        'Callback', @(src,event) buttonCallback(k, fig));
end

end

function buttonCallback(k, fig)
switch k
    case 1
        disp('Setup / Run Analysis');
        icatb_fb_setup;
    case 2
        disp('Post-processing');
        icatb_fb_post_process();
    case 3
        disp('Display');
        icatb_fb_display()
    case 4
        disp('Stats');
        icatb_fb_stats()
    case 5
        close(fig);
end
end

